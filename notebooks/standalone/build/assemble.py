"""Assemble `afa_lab.py` from the block sources in `blocks/`.

The blocks are kept as separate, importable modules so they can be unit-tested
directly; the shipped notebooks import one flat module instead, so a reader has
one file to open rather than six. Running this script regenerates that file —
edit `blocks/*.py`, never `afa_lab.py`.
"""

from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
BLOCKS = HERE / "blocks"
OUTPUT = HERE.parent / "afa_lab.py"

ORDER = ["data", "features", "backtest", "strategies", "models", "plots"]

HEADER = '''"""afa_lab — a self-contained toolkit for the standalone strategy notebooks.

Everything the notebooks in this folder need: HuggingFace ingestion, cleaning,
feature construction, six strategies, a target-weight backtester and the charts.

**This module deliberately does not import `portfolio_agent`.** The notebooks
are a standalone re-implementation of the strategies the framework ships, so
they can be run, read and modified without installing the platform — copy this
folder anywhere and it works. Where a design choice mirrors the framework's, the
comment says why the choice is right rather than citing the framework.

Generated by `build/assemble.py` from `build/blocks/*.py`. Edit the blocks.

Requires: pandas, numpy, pyarrow, matplotlib, huggingface_hub, torch.
"""

from __future__ import annotations

import math
import os
import warnings
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

import numpy as np
import pandas as pd

try:
    import torch
    import torch.nn as nn
    import torch.nn.functional as F
    TORCH_AVAILABLE = True
except ImportError:  # the two learned strategies need it; the other four do not
    TORCH_AVAILABLE = False

import matplotlib.pyplot as plt
import matplotlib.ticker as mticker

'''

# Import lines are hoisted into the header above; stripping them from each block
# keeps the assembled module from re-importing the same names six times.
DROP_PATTERNS = [
    re.compile(r"^from __future__ import .*$"),
    re.compile(r"^import (numpy|pandas|math|os|warnings|torch)(\s|$).*$"),
    re.compile(r"^import (torch\.nn|torch\.nn\.functional|matplotlib\.pyplot|matplotlib\.ticker) as .*$"),
    re.compile(r"^from (dataclasses|typing|pathlib) import .*$"),
    re.compile(r"^from torch import .*$"),
]


def strip_imports(source: str) -> str:
    """Remove the module-level imports the assembled header already provides."""
    lines, out = source.splitlines(), []
    for line in lines:
        if any(pattern.match(line) for pattern in DROP_PATTERNS):
            continue
        out.append(line)

    # Collapse the blank runs left where imports were removed.
    cleaned, blanks = [], 0
    for line in out:
        if line.strip():
            blanks = 0
            cleaned.append(line)
        else:
            blanks += 1
            if blanks <= 2:
                cleaned.append(line)
    return "\n".join(cleaned).strip("\n")


def build() -> Path:
    parts = [HEADER]
    for name in ORDER:
        source = (BLOCKS / f"{name}.py").read_text()
        parts.append(strip_imports(source))
        parts.append("\n")
    OUTPUT.write_text("\n".join(parts).rstrip() + "\n")
    return OUTPUT


if __name__ == "__main__":
    path = build()
    print(f"wrote {path} ({len(path.read_text().splitlines())} lines)")
