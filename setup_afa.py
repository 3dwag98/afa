def print_success(message: str):
    """Print a success message in green."""
    print(f"{Colors.GREEN}✓{Colors.RESET} {message}")

def print_error(message: str):
    """Print an error message in red."""
    print(f"{Colors.RED}✗{Colors.RESET} {message}")

def print_warning(message: str):
    """Print a warning message in yellow."""
    print(f"{Colors.YELLOW}⚠{Colors.RESET} {message}")

def print_info(message: str):
    """Print an info message in blue."""
    print(f"{Colors.BLUE}ℹ{Colors.RESET} {message}")

def print_section(message: str):
    """Print a section header."""
    print(f"\n{Colors.MAGENTA}{Colors.BOLD}=== {message} ==={Colors.RESET}\n")

# ============================================================================
# System Detection
# ============================================================================
def get_os() -> str:
    """Detect and return the operating system."""
    system = platform.system()
    if system == "Windows":
        return "windows"
    elif system == "Darwin":
        return "macos"
    elif system == "Linux":
        return "linux"
    else:
        return "unknown"

def get_os_display_name() -> str:
    """Get a human-readable OS name."""
    os_name = get_os()
    if os_name == "windows":
        return "Windows"
    elif os_name == "macos":
        return "macOS"
    elif os_name == "linux":
        return "Linux"
    else:
        return f"Unknown ({platform.system()})"

# ============================================================================
# Prerequisites Check
# ============================================================================
def run_command(cmd: list, capture_output: bool = True, check: bool = False) -> Tuple[int, str, str]:
    """
    Run a shell command and return exit code, stdout, stderr.
    
    Args:
        cmd: Command as list of strings
        capture_output: Whether to capture stdout/stderr
        check: Whether to raise exception on non-zero exit
    
    Returns:
        Tuple of (exit_code, stdout, stderr)
    """
    try:
        result = subprocess.run(
            cmd,
            capture_output=capture_output,
            text=True,
            check=check
        )
        return result.returncode, result.stdout or "", result.stderr or ""
    except subprocess.CalledProcessError as e:
        return e.returncode, e.stdout or "", e.stderr or ""
    except FileNotFoundError:
        return -1, "", f"Command not found: {cmd[0]}"

def check_git() -> bool:
    """Check if git is installed and accessible."""
    print_info("Checking for git...")
    exit_code, stdout, stderr = run_command(["git", "--version"])
    if exit_code == 0:
        print_success(f"Git found: {stdout.strip()}")
        return True
    else:
        print_error("Git is not installed or not in PATH")
        return False

def check_docker() -> bool:
    """Check if Docker is installed and daemon is running."""
    print_info("Checking for Docker...")
    exit_code, stdout, stderr = run_command(["docker", "info"])
    if exit_code == 0:
        print_success("Docker is installed and running")
        return True
    else:
        print_error("Docker is not installed or daemon is not running")
        if stderr:
            print_warning(f"Docker error: {stderr.strip()}")
        return False

def check_docker_compose() -> bool:
    """Check if docker compose (v2) is available."""
    print_info("Checking for Docker Compose (v2)...")
    # Try 'docker compose' (v2 syntax)
    exit_code, stdout, stderr = run_command(["docker", "compose", "version"])
    if exit_code == 0:
        print_success(f"Docker Compose found: {stdout.strip()}")
        return True
    
    # Fallback: try 'docker-compose' (v1 syntax)
    exit_code, stdout, stderr = run_command(["docker-compose", "--version"])
    if exit_code == 0:
        print_warning(f"Docker Compose (v1) found: {stdout.strip()}")
        print_info("Consider upgrading to Docker Compose v2 ('docker compose')")
        return True
    
    print_error("Docker Compose is not installed")
    return False

