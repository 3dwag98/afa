# ============================================================================
# Repository Management
# ============================================================================
def clone_or_pull_repo(project_dir: Path) -> bool:
    """Clone the repository or pull latest changes if it exists."""
    print_section("Repository Setup")
    
    if project_dir.exists():
        print_info(f"Directory '{project_dir}' already exists")
        print_info("Pulling latest changes...")
        
        # Verify it's a git repository
        git_dir = project_dir / ".git"
        if not git_dir.exists():
            print_error(f"'{project_dir}' exists but is not a git repository")
            return False
        
        exit_code, stdout, stderr = run_command(
            ["git", "pull"],
            capture_output=False,
            check=False
        )
        
        if exit_code == 0:
            print_success("Repository updated successfully")
            return True
        else:
            print_error("Failed to pull latest changes")
            if stderr:
                print_warning(stderr)
            return False
    else:
        print_info(f"Cloning repository from {REPO_URL}...")
        exit_code, stdout, stderr = run_command(
            ["git", "clone", REPO_URL, str(project_dir)],
            capture_output=False,
            check=False
        )
        
        if exit_code == 0:
            print_success(f"Repository cloned to '{project_dir}'")
            return True
        else:
            print_error("Failed to clone repository")
            if stderr:
                print_warning(stderr)
            return False

# ============================================================================
# Directory & Permission Setup
# ============================================================================
def create_directories(project_dir: Path) -> bool:
    """Create required directories inside the project root."""
    print_section("Creating Required Directories")
    
    all_created = True
    for dir_path in REQUIRED_DIRS:
        full_path = project_dir / dir_path
        try:
            full_path.mkdir(parents=True, exist_ok=True)
            print_success(f"Created: {dir_path}")
        except Exception as e:
            print_error(f"Failed to create {dir_path}: {e}")
            all_created = False
    
    return all_created

def fix_permissions(project_dir: Path) -> bool:
    """Fix permissions for Docker bind mounts (Linux only)."""
    os_name = get_os()
    
    print_section("Setting Directory Permissions")
    print_info(f"Detected OS: {get_os_display_name()}")
    
    if os_name != "linux":
        print_info("Docker Desktop handles volume permissions automatically on this OS")
        print_success("Skipping permission changes")
        return True
    
    # Linux-specific permission fix
    print_warning("Linux detected: Setting ownership for Docker containers (UID 50000)")
    print_info("This requires sudo privileges for Airflow compatibility")
    
    dirs_to_chown = ["data", "output", "logs", "airflow"]
    chown_cmd = ["sudo", "chown", "-R", f"{AIRFLOW_UID}:{AIRFLOW_GID}"]
    
    for dir_name in dirs_to_chown:
        dir_path = project_dir / dir_name
        if dir_path.exists():
            cmd = chown_cmd + [str(dir_path)]
            print_info(f"Running: {' '.join(cmd)}")
            
            exit_code, stdout, stderr = run_command(cmd, capture_output=False, check=False)
            
            if exit_code == 0:
                print_success(f"Ownership set for {dir_name}")
            else:
                print_error(f"Failed to set ownership for {dir_name}")
                print_warning("You may need to manually run: sudo chown -R 50000:0 " + dir_name)
                return False
    
    print_success("Permissions configured for Docker containers")
    return True

# ============================================================================
# Environment File Setup
# ============================================================================
def create_env_file(project_dir: Path) -> bool:
    """Create default .env file if it doesn't exist."""
    print_section("Environment Configuration")
    
    env_file = project_dir / ".env"
    
    if env_file.exists():
        print_info(f".env file already exists at {env_file}")
        print_warning("Skipping .env creation to preserve existing configuration")
        return True
    
    try:
        with open(env_file, 'w') as f:
            f.write(DEFAULT_ENV_CONTENT)
        print_success(f"Created default .env file at {env_file}")
        return True
    except Exception as e:
        print_error(f"Failed to create .env file: {e}")
        return False

# ============================================================================
# Docker Build
# ============================================================================
def build_docker_images(project_dir: Path) -> bool:
    """Build Docker images using docker compose."""
    print_section("Building Docker Images")
    
    print_info("This may take several minutes depending on your system...")
    response = input(f"{Colors.YELLOW}Do you want to build Docker images now? (y/n): {Colors.RESET}").strip().lower()
    
    if response not in ['y', 'yes']:
        print_info("Skipping Docker build. You can build later with:")
        print(f"  cd {project_dir}")
        print("  docker compose --profile airflow build")
        return True
    
    print_info("Starting Docker build...")
    
    # Change to project directory for build
    original_cwd = os.getcwd()
    try:
        os.chdir(project_dir)
        exit_code, stdout, stderr = run_command(
            ["docker", "compose", "--profile", "airflow", "build"],
            capture_output=False,
            check=False
        )
        
        if exit_code == 0:
            print_success("Docker images built successfully!")
            return True
        else:
            print_error("Docker build failed")
            print_info("You can try building manually with:")
            print(f"  cd {project_dir}")
            print("  docker compose --profile airflow build")
            return False
    except Exception as e:
        print_error(f"Error during Docker build: {e}")
        return False
    finally:
        os.chdir(original_cwd)

# ============================================================================
# Main Setup Flow
# ============================================================================
def main():
    """Main entry point for the setup script."""
    print_banner()
    
    # Get current working directory
    cwd = Path.cwd()
    project_dir = cwd / PROJECT_DIR_NAME
    
    # Detect OS
    os_name = get_os()
    print_info(f"Running on: {get_os_display_name()}")
    print_info(f"Working directory: {cwd}")
    print()
    
    # Step 1: Check Prerequisites
    print_section("Prerequisites Check")
    
    checks_passed = True
    
    if not check_git():
        checks_passed = False
    
    if not check_docker():
        checks_passed = False
    
    if not check_docker_compose():
        checks_passed = False
    
    if not checks_passed:
        print_error("One or more prerequisites are missing")
        print_installation_guide(os_name)
        sys.exit(1)
    
    print_success("All prerequisites are satisfied!")
    
    # Step 2: Clone or Pull Repository
    if not clone_or_pull_repo(project_dir):
        print_error("Repository setup failed")
        sys.exit(1)
    
    # Step 3: Create Required Directories
    if not create_directories(project_dir):
        print_error("Directory creation failed")
        sys.exit(1)
    
    # Step 4: Fix Permissions (Linux only)
    if not fix_permissions(project_dir):
        print_warning("Permission setup had issues, but continuing...")
    
    # Step 5: Create Environment File
    if not create_env_file(project_dir):
        print_warning("Environment file creation failed, but continuing...")
    
    # Step 6: Docker Build (Optional)
    build_docker_images(project_dir)
    
    # Final Summary
    print_section("Setup Complete!")
    print(f"""
{Colors.GREEN}AFA setup completed successfully!{Colors.RESET}

Next steps:
  1. Review and customize the .env file if needed:
     {project_dir / '.env'}
  
  2. Start the services:
     cd {project_dir}
     docker compose --profile airflow up -d
  
  3. Access Airflow UI:
     http://localhost:8080
     (Default credentials: admin / admin)

For more information, see the README.md file.
""")

if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print(f"\n\n{Colors.YELLOW}Setup interrupted by user.{Colors.RESET}")
        sys.exit(130)
    except Exception as e:
        print(f"\n{Colors.RED}Fatal error: {e}{Colors.RESET}")
        sys.exit(1)
